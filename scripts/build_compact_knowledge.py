#!/usr/bin/env python3
import argparse, gzip, hashlib, json, math, re, unicodedata, zlib
from collections import Counter, defaultdict
from pathlib import Path

TOKEN_RE=re.compile(r"[a-z0-9][a-z0-9._-]{2,31}")
# Match the same literal OBD/DF codes as the client, including spaces introduced
# by OCR. Do not guess ambiguous O/I characters or promote them to evidence.
DTC_RE=re.compile(r"\b(?:[PBCU][ \t]*[0-3](?:[ \t]*[0-9A-F]){3}|DF[ \t]*\d(?:[ \t]*\d){2,3})\b",re.I)
CANONICAL_DTC_RE=re.compile(r"(?:[PBCU][0-3][0-9A-F]{3}|DF\d{3,4})",re.I)
STOP={
"para","com","sem","que","uma","uns","das","dos","de","da","do","em","no","na","nos","nas","por","pra","pro",
"carro","veiculo","veículo","motor","quero","como","qual","quais","esta","está","este","essa","esse","isso","aqui",
"mais","menos","muito","muita","muitos","muitas","ser","ter","tem","foi","sao","são","the","and","for","with","from",
"this","that","into","not","are","has","have","you","your","page","pagina","página","manual","treinamento"
}
# Dedicated literal source windows keep component evidence beyond truncated previews.
# Extraction status and application identity must still be checked by the client.
FOCUS_PATTERNS={
    "detonacao": re.compile(r"\b(?:detonac[a-z]*|knock\s+sens(?:or|ors)|sensor\s+de\s+picado)\b"),
    "map": re.compile(r"\b(?:sensor\s+(?:de\s+)?pressao\s+absoluta|pressao\s+absoluta\s+(?:do\s+)?coletor|manifold\s+absolute\s+pressure|sensor\s+map)\b"),
    "lambda": re.compile(r"\b(?:sonda\s+lambda|sensor\s+(?:de\s+)?lambda|sensor\s+(?:de\s+)?oxigenio|oxygen\s+sensor)\b"),
    "canister": re.compile(r"\b(?:canister|canistor|valvula\s+(?:de\s+)?purga|evaporative\s+purge)\b"),
    "alimentacao": re.compile(r"\b(?:rele\s+principal|alimentacao\s+(?:da\s+)?(?:ecu|uce|central|computador)|aterramento\s+(?:da\s+)?(?:ecu|uce|central)|fusivel\s+(?:da\s+)?injecao)\b"),
    "injetor": re.compile(r"\b(?:injetor(?:es)?|injector(?:s)?|bico\s+injetor)\b"),
    "ignicao": re.compile(r"\b(?:bobina(?:s)?\s+(?:de\s+)?ignicao|ignition\s+coil)\b"),
}

MAX_TERMS_PER_RECORD=170
MAX_POSTINGS_PER_TERM=160
RECORD_BUCKETS=64
TEXT_PREVIEW=2600

def norm(s):
    s=unicodedata.normalize("NFD",str(s or ""))
    s="".join(ch for ch in s if unicodedata.category(ch)!="Mn")
    return s.lower()

def tokens(text):
    terms=set(t for t in TOKEN_RE.findall(norm(text)) if t not in STOP and not t.isdigit())
    terms.update(code.lower() for code in codes_from(text))
    return terms

def codes_from(text):
    return {re.sub(r"[ \t]","",m.group()).upper() for m in DTC_RE.finditer(str(text or ""))}

def read_records(knowledge):
    manifest=json.loads((knowledge/"manifest.json").read_text(encoding="utf-8"))
    recs=[]
    for shard in manifest.get("shards",[]):
        p=knowledge/"brain"/shard["file"]
        with gzip.open(p,"rt",encoding="utf-8") as f:
            for line_number,line in enumerate(f,1):
                line=line.strip()
                if not line: continue
                try: r=json.loads(line)
                except json.JSONDecodeError as exc:
                    raise ValueError(f"Invalid record in {p}:{line_number}") from exc
                if not isinstance(r,dict) or (r.get("text") and not isinstance(r["text"],str)):
                    raise ValueError(f"Invalid record in {p}:{line_number}")
                if not r.get("text"): continue
                recs.append(r)
    return manifest,recs

def record_bucket(path):
    return zlib.crc32(str(path or "").encode("utf-8")) % RECORD_BUCKETS

def window_around(text,needle,width=950):
    raw=" ".join(str(text or "").split())
    if not raw: return ""
    pos=norm(raw).find(norm(needle))
    if pos<0 and CANONICAL_DTC_RE.fullmatch(needle):
        pos=next((m.start() for m in DTC_RE.finditer(raw)
                  if re.sub(r"[ \t]","",m.group()).upper()==needle.upper()),-1)
    if pos<0: return raw[:width]
    start=max(0,pos-width//3)
    end=min(len(raw),start+width)
    return ("…" if start else "")+raw[start:end]+("…" if end<len(raw) else "")

def compact_record(idx,r):
    text=" ".join(str(r.get("text","")).split())
    # Extraction confidence does not establish a source's provenance or verify a
    # mechanical fact. Missing provenance remains unknown in every output.
    truth=r.get("truth_status") or "unknown"
    return {
        "id":idx,
        "path":r.get("path",""),
        "page":r.get("page"),
        "chunk":r.get("chunk"),
        "text":text[:TEXT_PREVIEW],
        "method":r.get("method"),
        "confidence":round(float(r.get("confidence") or 0),4),
        "truth_status":truth,
        "sha256":r.get("sha256","")
    }

def prefix(term):
    t=re.sub(r"[^a-z0-9]","",term)
    if len(t)>=2: return t[:2]
    if len(t)==1: return t+"0"
    return "__"

def remove_stale_outputs(directory,pattern,expected):
    # Only remove files generated by this builder. An existing output directory
    # may contain notes or other user files that do not belong to the index.
    for path in directory.iterdir():
        if path.is_file() and re.fullmatch(pattern,path.name) and path.name not in expected:
            path.unlink()

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--knowledge-dir",required=True)
    ap.add_argument("--out",required=True)
    args=ap.parse_args()
    knowledge=Path(args.knowledge_dir)
    out=Path(args.out)
    source_manifest,recs=read_records(knowledge)
    print("records",len(recs),flush=True)

    dfs=Counter()
    record_terms=[]
    for r in recs:
        path_terms=tokens(r.get("path",""))
        text_terms=tokens(r.get("text",""))
        ts=path_terms|text_terms
        record_terms.append((path_terms,text_terms))
        dfs.update(ts)

    n=max(1,len(recs))
    postings=defaultdict(list)
    dtc_entries=defaultdict(list)
    focus_entries=defaultdict(list)
    buckets=[{} for _ in range(RECORD_BUCKETS)]
    record_map=[0]*len(recs)

    for idx,r in enumerate(recs):
        path_terms,text_terms=record_terms[idx]
        codes=codes_from(r.get("text",""))|codes_from(r.get("path",""))
        scored=[]
        for t in (path_terms|text_terms):
            df=dfs[t]
            if df<1 or df>max(4500,int(n*.35)): continue
            idf=math.log((n+1)/(df+1))+1.0
            bonus=2.5 if t in path_terms else 0.0
            if CANONICAL_DTC_RE.fullmatch(t): bonus+=8
            if any(ch.isdigit() for ch in t): bonus+=1.5
            scored.append((idf+bonus,t))
        scored.sort(reverse=True)
        selected=[t for _,t in scored[:MAX_TERMS_PER_RECORD]]

        b=record_bucket(r.get("path",""))
        record_map[idx]=b
        evidence=compact_record(idx,r)
        buckets[b][str(idx)]=evidence

        # Preserve the source's actual text around a named component, without
        # claiming the passage is necessarily applicable to this vehicle.
        full_text=str(r.get("text",""))
        normalized=norm(full_text)
        for topic,pattern in FOCUS_PATTERNS.items():
            match=pattern.search(normalized)
            if not match: continue
            entry={k:evidence[k] for k in (
                "id","path","page","chunk","method","confidence","truth_status","sha256"
            )}
            entry["snippet"]=window_around(full_text,match.group(0),850)
            focus_entries[topic].append(entry)

        for t in selected:
            arr=postings[t]
            if len(arr)<MAX_POSTINGS_PER_TERM: arr.append(idx)
        for code in sorted(codes):
            arr=dtc_entries[code]
            if len(arr)<160:
                arr.append({
                    "id":idx,
                    "path":evidence["path"],
                    "page":evidence["page"],
                    "chunk":evidence["chunk"],
                    "snippet":window_around(r.get("text",""),code),
                    "method":evidence["method"],
                    "confidence":evidence["confidence"],
                    "truth_status":evidence["truth_status"],
                    "sha256":evidence["sha256"]
                })

        if idx and idx%2500==0:
            print("indexed",idx,"/",n,flush=True)

    out.mkdir(parents=True,exist_ok=True)
    focus_dir=out/"focus";focus_dir.mkdir(exist_ok=True)
    for topic,rows in sorted(focus_entries.items()):
        (focus_dir/f"{topic}.json").write_text(
            json.dumps(rows,ensure_ascii=False,separators=(",",":")),encoding="utf-8"
        )
    remove_stale_outputs(focus_dir,r"[a-z]+\.json",
                         {f"{name}.json" for name in focus_entries})
    records_dir=out/"records";records_dir.mkdir(exist_ok=True)
    for b,data in enumerate(buckets):
        (records_dir/f"r{b:02d}.json").write_text(json.dumps(data,ensure_ascii=False,separators=(",",":"),sort_keys=True),encoding="utf-8")
    remove_stale_outputs(records_dir,r"r\d+\.json",{f"r{b:02d}.json" for b in range(RECORD_BUCKETS)})
    (out/"record-map.json").write_text(json.dumps(record_map,separators=(",",":")),encoding="utf-8")

    by_prefix=defaultdict(dict)
    for term,ids in postings.items():
        by_prefix[prefix(term)][term]=ids
    terms_dir=out/"terms";terms_dir.mkdir(exist_ok=True)
    for pre,data in sorted(by_prefix.items()):
        (terms_dir/f"{pre}.json").write_text(json.dumps(data,ensure_ascii=False,separators=(",",":"),sort_keys=True),encoding="utf-8")
    remove_stale_outputs(terms_dir,r"[a-z0-9_]{2}\.json",{f"{pre}.json" for pre in by_prefix})

    dtc_dir=out/"dtc";dtc_dir.mkdir(exist_ok=True)
    for code,rows in sorted(dtc_entries.items()):
        payload={"code":code,"records":rows}
        (dtc_dir/f"{code}.json").write_text(json.dumps(payload,ensure_ascii=False,separators=(",",":"),sort_keys=True),encoding="utf-8")
    remove_stale_outputs(dtc_dir,r"(?:[PBCU][0-9A-F]{4}|DF\d{3,4})\.json",{f"{code}.json" for code in dtc_entries})

    revision=hashlib.sha256()
    generated=[out/"record-map.json"]
    for directory in (records_dir,terms_dir,dtc_dir,focus_dir):
        generated.extend(directory.glob("*.json"))
    for artifact in sorted(generated):
        revision.update(artifact.relative_to(out).as_posix().encode("utf-8")+b"\0")
        with artifact.open("rb") as stream:
            for block in iter(lambda:stream.read(1024*1024),b""):
                revision.update(block)

    truth_counts=Counter((r.get("truth_status") or "unknown") for r in recs)
    manifest={
        "schema_version":1,
        "mode":"compact-lexical",
        "index_revision":revision.hexdigest(),
        "source_archive":source_manifest.get("archive"),
        "source_archive_sha256":source_manifest.get("archive_sha256"),
        "source_schema_version":source_manifest.get("schema_version"),
        "records":len(recs),
        "record_buckets":RECORD_BUCKETS,
        "term_files":len(by_prefix),
        "terms":len(postings),
        "dtcs":len(dtc_entries),
        "text_preview_chars":TEXT_PREVIEW,
        "focused_topics":{name:len(rows) for name,rows in sorted(focus_entries.items())},
        "truth_counts":dict(truth_counts),
        "truth_policy":source_manifest.get("truth_policy",{}),
        "heavy_shards_required_by_client":False
    }
    (out/"manifest.json").write_text(json.dumps(manifest,ensure_ascii=False,indent=2,sort_keys=True),encoding="utf-8")
    (out/"README.md").write_text(
        "# thIAguinho Compact Knowledge\n\n"
        "Indice lexical compacto gerado automaticamente a partir do branch knowledge.\n"
        "O aplicativo consulta apenas termos, DTCs e pequenos buckets de evidencias; nao baixa os shards pesados.\n"
        "Cada evidencia preserva caminho, pagina, metodo, confianca, SHA-256 e truth_status.\n",
        encoding="utf-8"
    )
    print(json.dumps(manifest,ensure_ascii=False,indent=2))

if __name__=="__main__":
    main()
